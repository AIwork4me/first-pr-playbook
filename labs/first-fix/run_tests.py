import unittest

from buggy import normalize_title


class NormalizeTitleTests(unittest.TestCase):

    def test_strips_and_collapses_inner_spaces(self):
        self.assertEqual(
            normalize_title("  fix  typo   in docs  "),
            "fix typo in docs",
        )

    def test_already_normalized_title_is_unchanged(self):
        self.assertEqual(normalize_title("fix typo in docs"), "fix typo in docs")

    def test_whitespace_only_title_becomes_empty(self):
        self.assertEqual(normalize_title("   "), "")

    def test_collapses_tabs_and_newlines_to_single_spaces(self):
        self.assertEqual(normalize_title("fix\ttypo\nin  docs"), "fix typo in docs")


if __name__ == "__main__":
    unittest.main(verbosity=2)
